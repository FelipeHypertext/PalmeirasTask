            <h3>O Clube</h3>
            <p>
                A Sociedade Esportiva Palmeiras é um dos maiores clubes do futebol brasileiro.
                Fundada em 26 de agosto de 1914, a equipe tem sede em São Paulo e é uma das
                mais vitoriosas do país, com dezenas de títulos nacionais e internacionais.
            </p>
        </article>

        <article class="sobre-card">
            <h3>O Sistema</h3>
            <p>
                Este é o gerenciador de tarefas interno do Palmeiras FC. Permite que a
                comissão técnica e os jogadores acompanhem as atividades diárias, treinos,
                reuniões e demais compromissos do clube de forma organizada.
            </p>
        </article>

        <article class="sobre-card">
            <h3>Funcionalidades</h3>
            <ul>
                <li>Cadastro e gerenciamento de tarefas</li>
                <li>Atribuição por responsável</li>
                <li>Controle de status (pendente / em andamento / concluída)</li>
                <li>Publicação de notícias do clube</li>
                <li>Gerenciamento de jogadores e comissão técnica</li>
            </ul>
        </article>

        <article class="sobre-card">
            <h3>Acesso</h3>
            <p>
                O sistema possui dois níveis de acesso:
            </p>
            <ul>
                <li><strong>Admin (Técnico)</strong> — gerencia tarefas, usuários e notícias</li>
                <li><strong>Membro (Jogador)</strong> — visualiza tarefas e notícias</li>
            </ul>
